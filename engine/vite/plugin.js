// Vite plugin that turns a folder of projects (tracks) into the engine's
// input, so a track never needs an edit in the studio:
//
//   virtual:lms-projects  code of each project: project.json, components/*.jsx|js,
//                         assets/*.css (fonts come in through @font-face there)
//   /p/<slug>/<path>      the project folder itself, served as static files:
//                         build/*.json, audio, images, fetched media (.media/)
//
// LMS_PROJECTS  folder that holds the projects (default: ./tracks)
// LMS_TRACK     build only this project (renders do; the dev server lists all)
import { createReadStream, existsSync, readdirSync, statSync } from 'node:fs'
import { extname, join, resolve, sep } from 'node:path'

export const MIME = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.svg': 'image/svg+xml',
  '.gif': 'image/gif',
  '.mp3': 'audio/mpeg',
  '.m4a': 'audio/mp4',
  '.wav': 'audio/wav',
  '.flac': 'audio/flac',
  '.ogg': 'audio/ogg',
  '.mp4': 'video/mp4',
  '.webm': 'video/webm',
  '.mov': 'video/quicktime',
}

export function listProjects(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((d) => existsSync(join(dir, d, 'project.json')))
    .sort()
}

const files = (dir, re) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => re.test(f) && statSync(join(dir, f)).isFile())
        .sort()
    : []

function moduleCode(dir, slugs) {
  const entry = (slug) => {
    const root = join(dir, slug)
    const comps = files(join(root, 'components'), /\.(jsx?|tsx?)$/)
    const css = files(join(root, 'assets'), /\.css$/)
    const abs = (...p) => JSON.stringify(join(root, ...p))
    return `${JSON.stringify(slug)}: {
    config: () => import(${abs('project.json')}).then((m) => m.default),
    components: {${comps.map((f) => `\n      ${JSON.stringify(f)}: () => import(${abs('components', f)}),`).join('')}
    },
    styles: () => Promise.all([${css.map((f) => `import(${abs('assets', f)})`).join(', ')}]),
  }`
  }
  return `// generated by engine/vite/plugin.js
export const PROJECTS_DIR = ${JSON.stringify(dir)}
export default {
  ${slugs.map(entry).join(',\n  ')}
}
`
}

// Serves <dir>/<slug>/<path> under /p/; shared by the dev server and render.mjs.
export function serveProjects(dir) {
  const root = resolve(dir)
  return (req, res, next) => {
    const path = decodeURIComponent(new URL(req.url, 'http://x').pathname)
    const file = resolve(root, '.' + path)
    if (!file.startsWith(root + sep) || !existsSync(file) || !statSync(file).isFile()) {
      if (next) return next()
      res.writeHead(404).end()
      return
    }
    const size = statSync(file).size
    const type = MIME[extname(file).toLowerCase()] ?? 'application/octet-stream'
    // ranges, so <audio>/<video> can seek in the dev preview
    const m = /bytes=(\d*)-(\d*)/.exec(req.headers.range ?? '')
    if (m) {
      const start = m[1] ? Number(m[1]) : 0
      const end = m[2] ? Number(m[2]) : size - 1
      res.writeHead(206, { 'content-type': type, 'content-range': `bytes ${start}-${end}/${size}`, 'accept-ranges': 'bytes', 'content-length': end - start + 1 })
      createReadStream(file, { start, end }).pipe(res)
    } else {
      res.writeHead(200, { 'content-type': type, 'accept-ranges': 'bytes', 'content-length': size })
      createReadStream(file).pipe(res)
    }
  }
}

export default function lms({ projects, track }) {
  const dir = resolve(projects)
  const ID = 'virtual:lms-projects'
  return {
    name: 'lms-projects',
    config: () => ({ server: { fs: { allow: [dir] } } }),
    resolveId: (id) => (id === ID ? '\0' + ID : null),
    load(id) {
      if (id !== '\0' + ID) return null
      const slugs = track ? [track] : listProjects(dir)
      for (const s of slugs) if (!existsSync(join(dir, s, 'project.json'))) throw new Error(`no project.json in ${join(dir, s)}`)
      return moduleCode(dir, slugs)
    },
    configureServer(server) {
      server.middlewares.use('/p', serveProjects(dir))
      // a new or removed component / stylesheet changes the generated module
      server.watcher.add(dir)
      const touch = (f) => {
        if (!f.startsWith(dir) || !/[\\/](components|assets)[\\/]|project\.json$/.test(f)) return
        const mod = server.moduleGraph.getModuleById('\0' + ID)
        if (mod) server.reloadModule(mod)
      }
      server.watcher.on('add', touch)
      server.watcher.on('unlink', touch)
    },
  }
}
